import { readFileSync, writeFileSync } from 'node:fs'
import { stdout } from 'node:process'
import { URL } from 'node:url'

// Reproducible local seed only. This script never connects to a database.
const records = JSON.parse(
  readFileSync(
    new URL('../apps/mobile/src/discovery/osm-pilot.json', import.meta.url),
    'utf8',
  ),
)
const literal = (text) => "'" + text.replaceAll("'", "''") + "'"
const payload = literal(JSON.stringify(records))
const sourceId = 'd0000000-0000-4000-8000-000000000001'
const sql = `-- GENERATED by node scripts/osm-snapshot-sql.mjs. LOCAL DEVELOPMENT ONLY.
-- Real OSM snapshot, all records UNVERIFIED. ODbL-1.0; see docs/mobile-discovery.md.
begin;
insert into public.discovery_sources (id, kind, label, url, license, attribution)
values ('${sourceId}', 'osm', '© OpenStreetMap contributors · pilot snapshot',
 'https://www.openstreetmap.org/copyright', 'ODbL-1.0', '© OpenStreetMap contributors')
on conflict (id) do nothing;
create temporary table osm_snapshot on commit drop as
select value as record from jsonb_array_elements(${payload}::jsonb);
insert into public.discovery_parking (
 source_id, source_record_id, source_url, source_updated_at, name, kind, geometry,
 side, address, fees, hours, verification, published
)
select '${sourceId}', record->>'id', record->>'sourceUrl', (record->>'sourceUpdatedAt')::timestamptz,
 record->>'name', record->>'kind', extensions.st_setsrid(extensions.st_geomfromgeojson((record->'geometry')::text),4326),
 record->>'side', record->>'address', record->>'fees', record->>'hours', 'unverified', true
from osm_snapshot on conflict (source_id, source_record_id) do nothing;
insert into public.discovery_regulations (parking_id, source_id, description, source_url, observed_at, published)
select p.id, '${sourceId}', rule->>'description', rule->>'sourceUrl', (rule->>'observedAt')::timestamptz, true
from osm_snapshot s
join public.discovery_parking p on p.source_id = '${sourceId}' and p.source_record_id = s.record->>'id'
cross join lateral jsonb_array_elements(s.record->'regulations') as rule
where not exists (select 1 from public.discovery_regulations r where r.parking_id = p.id and r.description = rule->>'description');
commit;
`
writeFileSync(new URL('../supabase/seed-discovery.sql', import.meta.url), sql)
stdout.write(
  `Generated local discovery seed for ${records.length} OSM records\n`,
)
